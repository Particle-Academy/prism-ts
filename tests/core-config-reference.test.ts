import { readFileSync } from 'node:fs';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { Anthropic, FimRequest, Mistral, OpenAI, TextRequest } from '../src/index.js';
import type { HttpRequest, HttpTransport, JsonObject, JsonValue } from '../src/index.js';

interface Case {
  id: string;
  kind: 'config' | 'thinking' | 'fim';
  provider?: 'anthropic' | 'openai' | 'mistral';
  property?: string;
  env?: Record<string, string>;
  config?: Record<string, unknown>;
  defaultConfig?: JsonValue;
  thinking?: JsonValue;
  reasoning?: boolean;
  now?: number;
  headers?: Record<string, string>;
  expected: { value?: unknown; error?: string; thinking?: JsonValue; count?: number; text?: string; rates?: JsonValue };
}

// Generated by the canonical three native observers. These are actual PHP
// results; independent prewritten predictions were checked before generation.
const fixture = JSON.parse(readFileSync(new URL('./fixtures/provider-configuration.json', import.meta.url), 'utf8')) as {
  environment_names: string[];
  cases: { id: string; given: Omit<Case, 'id' | 'expected'>; result: { php: Case['expected'] } }[];
};
const providers = { anthropic: Anthropic, openai: OpenAI, mistral: Mistral };
const names: Record<string, string> = { api_key: 'apiKey', version: 'apiVersion', anthropic_beta: 'betaFeatures', api_format: 'apiFormat' };
afterEach(() => { vi.unstubAllEnvs(); vi.unstubAllGlobals(); vi.restoreAllMocks(); });

describe('installed PHP configuration observations (G230)', () => {
  for (const entry of fixture.cases) {
    const row = { id: entry.id, ...entry.given, expected: entry.result.php };
    it(row.id, async () => {
      vi.stubGlobal('fetch', () => { throw new Error('Unowned fetch in configuration corpus.'); });
      for (const name of fixture.environment_names) vi.stubEnv(name, undefined);
      for (const [name, value] of Object.entries(row.env ?? {})) vi.stubEnv(name, value);
      if (row.kind === 'config') {
        const config = Object.fromEntries(Object.entries(row.config ?? {}).map(([name, value]) => [names[name] ?? name, value]));
        const construct = (): Anthropic | OpenAI | Mistral => new providers[row.provider ?? 'anthropic'](config);
        if (row.expected.error !== undefined) {
          expect(construct).toThrow(TypeError);
        } else {
          const provider = construct();
          expect(Reflect.get(provider, row.property ?? '')).toEqual(row.expected.value);
        }
        return;
      }
      const calls: HttpRequest[] = [];
      const transport: HttpTransport = async (request) => {
        calls.push(request);
        if (row.kind === 'fim') return {
          status: 200, headers: row.headers ?? {}, rawBody: '',
          body: { id: 'fixture', model: 'fixture', choices: [{ message: { content: 'ok' }, finish_reason: 'stop' }], usage: { prompt_tokens: 1, completion_tokens: 1 } },
        };
        return { status: 200, headers: {}, rawBody: '', body: { id: 'fixture', model: 'fixture', content: [{ type: 'text', text: 'ok' }], stop_reason: 'end_turn', usage: {} } };
      };
      const config: Record<string, unknown> = { apiKey: 'synthetic', url: 'https://offline.invalid/v1', transport };
      if (row.kind === 'fim') {
        vi.spyOn(Date, 'now').mockReturnValue((row.now ?? 0) * 1000);
        const response = await new Mistral(config).fim(new FimRequest({ model: 'fixture', providerKey: 'mistral', prompt: 'prefix' }));
        expect(calls).toHaveLength(1);
        expect(calls[0]?.url).toBe('https://offline.invalid/v1/fim/completions');
        expect({ count: calls.length, text: response.text, rates: response.meta.rateLimits.map(rate => rate.toObject()) }).toEqual(row.expected);
        return;
      }
      if (Object.hasOwn(row, 'defaultConfig')) config.defaultThinkingBudget = row.defaultConfig;
      await new Anthropic(config).text(new TextRequest({ model: 'fixture', providerOptions: { thinking: row.thinking ?? null }, reasoningEnabled: row.reasoning ?? null }));
      expect(calls).toHaveLength(1);
      const body = JSON.parse(calls[0]?.body ?? '{}') as JsonObject;
      expect(body.thinking ?? null).toEqual(row.expected.thinking);
    });
  }

  it('does not consume or warn about a legacy beta when explicit null wins', () => {
    vi.stubEnv('ANTHROPIC_BETA', 'canonical-secret');
    vi.stubEnv('ANTHROPIC_BETA_FEATURES', 'legacy-secret');
    const warn = vi.spyOn(process, 'emitWarning').mockImplementation(() => undefined);
    expect(new Anthropic({ betaFeatures: null }).betaFeatures).toBeNull();
    expect(warn).not.toHaveBeenCalled();
  });

  it('consumes legacy beta once, with a value-free warning, only when canonical is absent', async () => {
    vi.resetModules();
    const { Anthropic: FreshAnthropic } = await import('../src/providers/anthropic/anthropic.js');
    const warn = vi.spyOn(process, 'emitWarning').mockImplementation(() => undefined);
    vi.stubEnv('ANTHROPIC_BETA', '');
    vi.stubEnv('ANTHROPIC_BETA_FEATURES', 'private-legacy-value');
    expect(new FreshAnthropic().betaFeatures).toBe('');
    expect(warn).not.toHaveBeenCalled();
    vi.stubEnv('ANTHROPIC_BETA', undefined);
    expect(new FreshAnthropic().betaFeatures).toBe('private-legacy-value');
    expect(new FreshAnthropic().betaFeatures).toBe('private-legacy-value');
    expect(warn).toHaveBeenCalledTimes(1);
    expect(JSON.stringify(warn.mock.calls)).toContain('ANTHROPIC_BETA');
    expect(JSON.stringify(warn.mock.calls)).not.toContain('private-legacy-value');
  });
});
